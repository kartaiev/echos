import { defineConfig, type Plugin } from "vitest/config";
import react from "@vitejs/plugin-react";

/**
 * Writes sw.js after the build: it precaches every built file (scripts, styles, the Neanes font, icons, manifest)
 * under a cache named after their contents, so the app works offline after its first load and a new build replaces
 * the old cache.
 */
function offlineServiceWorker(): Plugin {
  return {
    name: "echos-offline-service-worker",
    apply: "build",
    generateBundle(_, bundle) {
      const publicFiles = ["manifest.webmanifest", "icon.svg", "icon-192.png", "icon-512.png", "apple-touch-icon.png"];
      const files = ["./", ...Object.keys(bundle).filter((f) => f !== "sw.js"), ...publicFiles].sort();
      const hash = fnv1a();
      for (const name of Object.keys(bundle).sort()) {
        const item = bundle[name]!;
        hash.add(name).add(item.type === "chunk" ? item.code : item.source);
      }
      // The worker's own code counts too, so changing how it caches also replaces the cache.
      hash.add(serviceWorkerSource("", files));
      const cache = `echos-${hash.hex()}`;
      this.emitFile({ type: "asset", fileName: "sw.js", source: serviceWorkerSource(cache, files) });
    },
  };
}

/** A small content hash (FNV-1a, 32 bits): enough to name the cache after the build. */
function fnv1a() {
  let h = 0x811c9dc5;
  const step = (n: number) => (h = Math.imul(h ^ n, 0x01000193) >>> 0);
  const api = {
    add(value: string | Uint8Array) {
      if (typeof value === "string") for (let i = 0; i < value.length; i++) step(value.charCodeAt(i));
      else for (const byte of value) step(byte);
      return api;
    },
    hex: () => h.toString(16).padStart(8, "0"),
  };
  return api;
}

function serviceWorkerSource(cache: string, files: string[]): string {
  return `// Generated by vite.config.ts. Precaches the app; serves it cache-first, pages network-first.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(files)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith("echos-") && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    // The page itself: fresh when online, the cached copy when offline.
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put("./", copy));
          return response;
        })
        .catch(() => caches.match("./", { ignoreVary: true })),
    );
    return;
  }
  // Module scripts and fonts are requested with an Origin header; servers that answer "Vary: Origin" would
  // otherwise never match the precached copies.
  event.respondWith(caches.match(request, { ignoreVary: true }).then((cached) => cached ?? fetch(request)));
});
`;
}

export default defineConfig({
  // Relative paths, so the same build works at a domain root, under /echos/ on GitHub Pages, or embedded.
  base: "./",
  plugins: [react(), offlineServiceWorker()],
  test: {
    include: ["src/**/*.test.ts"],
  },
});
